const number1 = document.getElementById("Bit");
const number2 = document.getElementById("BitNum");
const Output = document.getElementById("Out");
const mybutton = document.getElementById("btn");

if (mybutton) {

    let Result = 0;
    mybutton.addEventListener("click", function BitConverter() {
        const number1Int = parseInt(number1.value);
        const number2Int = parseInt(number2.value);
        Result = number1Int * number2Int;
        Output.textContent = Result.toString();
    });
}

